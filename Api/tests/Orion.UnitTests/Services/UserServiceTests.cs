using FluentValidation;
using NSubstitute;
using Orion.Application.DTOs.Users;
using Orion.Application.Interfaces;
using Orion.Application.Services;
using Orion.Application.Validators;
using Orion.Domain.Entities;
using Orion.Domain.Enums;
using Orion.Domain.Exceptions;
using Orion.Domain.Interfaces;

namespace Orion.UnitTests.Services;

public sealed class UserServiceTests
{
    private readonly IUserRepository _userRepository = Substitute.For<IUserRepository>();
    private readonly IPasswordHasher _passwordHasher = Substitute.For<IPasswordHasher>();
    private readonly UserService _sut;

    public UserServiceTests()
    {
        _sut = new UserService(
            _userRepository,
            _passwordHasher,
            new RegisterUserRequestValidator(),
            new UpdateUserProfileRequestValidator());
    }

    private static RegisterUserRequest CreateValidRegisterRequest(
        string? username = null,
        string email = "Arthur.Pendragon@Orion.Realm",
        string password = "Orion!Spell2026") =>
        new(
            FirstName: "Arthur",
            MiddleName: "Pendragon",
            Email: email,
            Username: username,
            Password: password,
            ConfirmPassword: password,
            AcceptTerms: true);

    [Fact]
    public async Task RegisterAsync_WithValidRequest_CreatesLevel1AdventurerWithHashedPassword()
    {
        var request = CreateValidRegisterRequest();
        User? persistedUser = null;

        _userRepository.ExistsByEmailAsync("arthur.pendragon@orion.realm", Arg.Any<CancellationToken>())
            .Returns(false);
        _userRepository.ExistsByUsernameAsync("arthur_pendragon", Arg.Any<CancellationToken>())
            .Returns(false);
        _passwordHasher.Hash(request.Password).Returns("$2a$12$hashed_secret_value");
        _userRepository.When(repo => repo.AddAsync(Arg.Any<User>(), Arg.Any<CancellationToken>()))
            .Do(call => persistedUser = call.Arg<User>());

        var response = await _sut.RegisterAsync(request);

        Assert.NotNull(persistedUser);
        Assert.Equal("arthur.pendragon@orion.realm", response.Email);
        Assert.Equal("arthur_pendragon", response.Username);
        Assert.Equal("$2a$12$hashed_secret_value", persistedUser.PasswordHash);
        Assert.NotEqual(request.Password, persistedUser.PasswordHash);

        Assert.Equal(nameof(AuthProvider.Local), response.AuthProvider);
        Assert.Equal(nameof(UserRole.User), response.Role);
        Assert.Equal(nameof(PlanType.Free), response.PlanType);
        Assert.Equal(0, response.TotalXp);
        Assert.Equal(1, response.CurrentLevel);
        Assert.Equal(0, response.CurrentStreak);
        Assert.Equal(0, response.LongestStreak);
        Assert.Equal(0, response.Gems);
        Assert.True(response.IsActive);

        await _userRepository.Received(1).AddAsync(Arg.Any<User>(), Arg.Any<CancellationToken>());
        await _userRepository.Received(1).SaveChangesAsync(Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task RegisterAsync_WhenAutoGeneratedUsernameCollides_AppendsUniqueSuffix()
    {
        var request = CreateValidRegisterRequest(username: null);

        _userRepository.ExistsByEmailAsync(Arg.Any<string>(), Arg.Any<CancellationToken>()).Returns(false);
        _userRepository.ExistsByUsernameAsync("arthur_pendragon", Arg.Any<CancellationToken>()).Returns(true);
        _userRepository.ExistsByUsernameAsync(
                Arg.Is<string>(u => u.StartsWith("arthur_pendragon_", StringComparison.Ordinal)),
                Arg.Any<CancellationToken>())
            .Returns(false);
        _passwordHasher.Hash(Arg.Any<string>()).Returns("hashed");

        var response = await _sut.RegisterAsync(request);

        Assert.StartsWith("arthur_pendragon_", response.Username, StringComparison.Ordinal);
        Assert.True(response.Username.Length > "arthur_pendragon_".Length);
    }

    [Fact]
    public async Task RegisterAsync_WhenEmailAlreadyExists_ThrowsEmailAlreadyExistsException()
    {
        var request = CreateValidRegisterRequest();
        _userRepository.ExistsByEmailAsync("arthur.pendragon@orion.realm", Arg.Any<CancellationToken>())
            .Returns(true);

        await Assert.ThrowsAsync<EmailAlreadyExistsException>(() => _sut.RegisterAsync(request));

        _passwordHasher.DidNotReceive().Hash(Arg.Any<string>());
        await _userRepository.DidNotReceive().AddAsync(Arg.Any<User>(), Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task RegisterAsync_WhenExplicitUsernameExists_ThrowsUsernameAlreadyExistsException()
    {
        var request = CreateValidRegisterRequest(username: "TakenHero");

        _userRepository.ExistsByEmailAsync(Arg.Any<string>(), Arg.Any<CancellationToken>()).Returns(false);
        _userRepository.ExistsByUsernameAsync("takenhero", Arg.Any<CancellationToken>()).Returns(true);

        await Assert.ThrowsAsync<UsernameAlreadyExistsException>(() => _sut.RegisterAsync(request));

        await _userRepository.DidNotReceive().AddAsync(Arg.Any<User>(), Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task RegisterAsync_WithInvalidPassword_ThrowsValidationExceptionWithoutTouchingRepository()
    {
        var request = CreateValidRegisterRequest(password: "weak");

        await Assert.ThrowsAsync<ValidationException>(() => _sut.RegisterAsync(request));

        await _userRepository.DidNotReceive().ExistsByEmailAsync(Arg.Any<string>(), Arg.Any<CancellationToken>());
        await _userRepository.DidNotReceive().AddAsync(Arg.Any<User>(), Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task GetByIdAsync_WhenUserDoesNotExist_ThrowsUserNotFoundException()
    {
        var missingId = Guid.NewGuid();
        _userRepository.GetByIdAsync(missingId, Arg.Any<CancellationToken>()).Returns((User?)null);

        await Assert.ThrowsAsync<UserNotFoundException>(() => _sut.GetByIdAsync(missingId));
    }

    [Fact]
    public async Task GetPagedAsync_ReturnsPagedResponseWithCalculatedTotalPages()
    {
        var user = User.CreateLocal(
            "Arthur",
            "Pendragon",
            "arthur@orion.realm",
            "arthur_pendragon",
            "hash",
            DateTime.UtcNow);

        _userRepository.GetPagedAsync(1, 10, Arg.Any<CancellationToken>())
            .Returns((new List<User> { user }, 21));

        var result = await _sut.GetPagedAsync(0, 10);

        Assert.Equal(1, result.PageNumber);
        Assert.Equal(10, result.PageSize);
        Assert.Equal(21, result.TotalCount);
        Assert.Equal(3, result.TotalPages);
        Assert.Single(result.Items);
        Assert.Equal(user.Id, result.Items[0].Id);
    }

    [Fact]
    public async Task UpdateProfileAsync_WhenUsernameIsAvailable_UpdatesUserAndSaves()
    {
        var user = User.CreateLocal(
            "Arthur",
            null,
            "arthur@orion.realm",
            "arthur_v1",
            "hash",
            DateTime.UtcNow);

        var request = new UpdateUserProfileRequest(
            FirstName: "Arthur",
            MiddleName: "High King",
            Username: "King_Arthur",
            AvatarUrl: "https://orion.realm/avatar.png");

        _userRepository.GetByIdAsync(user.Id, Arg.Any<CancellationToken>()).Returns(user);
        _userRepository.ExistsByUsernameAsync("king_arthur", Arg.Any<CancellationToken>()).Returns(false);

        var response = await _sut.UpdateProfileAsync(user.Id, request);

        Assert.Equal("High King", response.MiddleName);
        Assert.Equal("king_arthur", response.Username);
        Assert.Equal("https://orion.realm/avatar.png", response.AvatarUrl);
        await _userRepository.Received(1).SaveChangesAsync(Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task SoftDeleteAsync_WhenUserExists_DeactivatesAccountAndSavesChanges()
    {
        var user = User.CreateLocal(
            "Arthur",
            null,
            "arthur@orion.realm",
            "arthur_v1",
            "hash",
            DateTime.UtcNow);

        _userRepository.GetByIdAsync(user.Id, Arg.Any<CancellationToken>()).Returns(user);

        await _sut.SoftDeleteAsync(user.Id);

        Assert.False(user.IsActive);
        await _userRepository.Received(1).SaveChangesAsync(Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task SoftDeleteAsync_WhenUserNotFound_ThrowsUserNotFoundException()
    {
        var missingId = Guid.NewGuid();
        _userRepository.GetByIdAsync(missingId, Arg.Any<CancellationToken>()).Returns((User?)null);

        await Assert.ThrowsAsync<UserNotFoundException>(() => _sut.SoftDeleteAsync(missingId));
    }

    [Fact]
    public async Task UpdateRoleAsync_WithValidAdminRole_UpdatesUserRoleAndSaves()
    {
        var user = User.CreateLocal(
            "Juan",
            "Maldonado",
            "juanjosemn160@gmail.com",
            "juanjo2409",
            "hash",
            DateTime.UtcNow);

        _userRepository.GetByIdAsync(user.Id, Arg.Any<CancellationToken>()).Returns(user);

        var response = await _sut.UpdateRoleAsync(user.Id, new UpdateUserRoleRequest("Admin"));

        Assert.Equal(nameof(UserRole.Admin), response.Role);
        Assert.Equal(UserRole.Admin, user.Role);
        await _userRepository.Received(1).SaveChangesAsync(Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task UpdateRoleAsync_WithInvalidRole_ThrowsDomainException()
    {
        await Assert.ThrowsAsync<DomainException>(() =>
            _sut.UpdateRoleAsync(Guid.NewGuid(), new UpdateUserRoleRequest("SuperWizard")));
    }
}
